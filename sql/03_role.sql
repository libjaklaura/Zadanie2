-- Run as a PostgreSQL administrator in database sql_injection.
CREATE ROLE sql_lab_app LOGIN PASSWORD 'SET_THIS_IN_PGADMIN_ONLY';
GRANT CONNECT ON DATABASE sql_injection TO sql_lab_app;
GRANT USAGE ON SCHEMA public TO sql_lab_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO sql_lab_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO sql_lab_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO sql_lab_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO sql_lab_app;

